// Installable app (#59): manifest and service worker. Both at the root:
// the worker controls only the paths under its own, and must cover the whole app.

type manifestIconOut struct {
	Src     string `json:"src"`
	Sizes   string `json:"sizes"`
	Type    string `json:"type"`
	Purpose string `json:"purpose"`
}

// handleManifest GET /manifest.webmanifest — color and icons follow the
// user's theme (the tema_colore cookie), the splash background the dark mode.
func (a *App) handleManifest(w http.ResponseWriter, r *http.Request) {
	ap := readAppearance(r)
	background := "#F7F8FA" // --bg chiaro
	if ap.Mode == "scuro" {
		background = "#16181C" // dark --bg
	}
	icon := func(kind, size, purpose string) manifestIconOut {
		return manifestIconOut{
			Src:     fmt.Sprintf("/static/icons/%s-%s-%s.png", kind, ap.Accent, size),
			Sizes:   size + "x" + size,
			Type:    "image/png",
			Purpose: purpose,
		}
	}
	m := map[string]any{
		"id":               "/",
		"name":             "Nutreek",
		"short_name":       "Nutreek",
		"description":      a.t(r, "public.manifest.description"),
		"lang":             i18n.FromContext(r.Context()),
		"dir":              "ltr",
		"start_url":        "/",
		"scope":            "/",
		"display":          "standalone",
		"theme_color":      web.AccentColor(ap.Accent),
		"background_color": background,
		"icons": []manifestIconOut{
			icon("icon", "192", "any"),
			icon("icon", "512", "any"),
			icon("maskable", "512", "maskable"),
		},
	}
	h := w.Header()
	h.Set("Content-Type", "application/manifest+json; charset=utf-8")
	h.Set("Cache-Control", "no-cache")
	h.Set("Vary", "Cookie")
	_ = json.NewEncoder(w).Encode(m)
}

// serviceWorkerJS: caches only /static (CSS, JS, fonts, icons), served from
// the cache and refreshed when the version changes. Pages, API and POST always
// go to the network: they hold the user's data and must be fresh.
const serviceWorkerJS = `// Nutreek — service worker (#59), generated by the server.
"use strict";
const CACHE = %q;

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((k) => k.startsWith("nutreek-static-") && k !== CACHE)
        .map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith("/static/")) return;
  event.respondWith(
    caches.open(CACHE).then((cache) =>
      cache.match(req).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) cache.put(req, res.clone());
        return res;
      }))
    )
  );
});
`

// handleServiceWorker GET /sw.js.
func (a *App) handleServiceWorker(w http.ResponseWriter, r *http.Request) {
	h := w.Header()
	h.Set("Content-Type", "text/javascript; charset=utf-8")
	h.Set("Cache-Control", "no-cache")
	fmt.Fprintf(w, serviceWorkerJS, "nutreek-static-"+web.StaticVersion())
}
